function localCare(text, lang) {
  const t = (text || "").toLowerCase().trim();
  if (/urdu|اردو|urdu mai|اردو میں|batao|batawo|bata do/.test(t)) {
    state.lang = "ur";
    localStorage.setItem("asj_lang", "ur");
    if ($("#lang")) $("#lang").value = "ur";
    apply();
    return replyFor(state.lastIntent || "hi", "ur");
  }
  let intent = "ask";
  if (/scam|fake|fraud|real website|نصب|احتيال|whatsapp|واتس|broker/.test(t)) intent = /website|site|سائٹ/.test(t) ? "site" : "scam";
  else if (/this site|ye site|website|سائٹ/.test(t)) intent = "site";
  else if (/qiwa|قوی|قوى|absher|ابشر/.test(t)) intent = "qiwa";
  else if (/iqama|اقامہ|إقامة|transfer|نقل|kafala/.test(t)) intent = "iqama";
  else if (/cv|resume|سيرة|سی وی/.test(t)) intent = "resume";
  else if (/job|work|نوکری|وظيفة|naukri|chahiye|چاہیے/.test(t)) intent = "job";
  else if (/apply|درخواست/.test(t)) intent = "apply";
  else if (/^(hi|hey|hello|salam|سلام|مرحبا)/.test(t) || t.length < 5) intent = "hi";
  state.lastIntent = intent;
  return replyFor(intent, lang);
}

const state = { lang: localStorage.getItem("asj_lang") || "ur", greeted: false, lastIntent: "hi" };
const $ = (s, r = document) => r.querySelector(s);

function apply() {
  const p = I[state.lang] || I.en;
  document.documentElement.lang = state.lang;
  document.body.classList.toggle("rtl", state.lang === "ur" || state.lang === "ar");
  document.querySelectorAll("[data-i]").forEach((el) => {
    const k = el.getAttribute("data-i");
    if (p[k] != null) el.innerHTML = p[k];
  });
  document.querySelectorAll("[data-i-ph]").forEach((el) => {
    const k = el.getAttribute("data-i-ph");
    if (p[k] != null) el.setAttribute("placeholder", p[k]);
  });
}

function show(id) {
  document.querySelectorAll(".view").forEach((v) => v.classList.toggle("on", v.id === id));
  const bar = document.getElementById("backbar");
  if (bar) bar.hidden = id === "home";
  window.scrollTo(0, 0);
}

function filterJobs(list) {
  const q = (($("#q") && $("#q").value) || "").toLowerCase();
  const city = ($("#city") && $("#city").value) || "";
  const visa = ($("#visa") && $("#visa").value) || "";
  return list.filter((j) => {
    if (city && !j.city.includes(city)) return false;
    if (visa && !(j.visa || "").includes(visa)) return false;
    if (q && !`${j.title} ${j.company} ${j.description}`.toLowerCase().includes(q)) return false;
    return true;
  });
}

async function loadJobs() {
  let data;
  try {
    const q = $("#q") ? $("#q").value : "";
    const city = $("#city") ? $("#city").value : "";
    const visa = $("#visa") ? $("#visa").value : "";
    const res = await fetch(`/api/jobs?q=${encodeURIComponent(q)}&city=${encodeURIComponent(city)}&visa=${encodeURIComponent(visa)}`);
    if (!res.ok) throw new Error("api");
    data = await res.json();
  } catch {
    data = { jobs: filterJobs(SAMPLE_JOBS) };
  }
  const box = $("#jobList");
  if (!box) return;
  const applyL = I[state.lang].apply;
  box.innerHTML = data.jobs
    .map(
      (j) => `
    <button class="card job" data-id="${j.id}">
      <span class="badge ${j.sample ? "badge-s" : "badge-v"}">${j.sample ? "SAMPLE" : "REVIEWED"}</span>
      <h3>${j.title}</h3>
      <p>${j.company}</p>
      <div class="meta">${j.city} · ${j.salary} · ${j.visa}</div>
      <div class="meta">${applyL}</div>
    </button>`
    )
    .join("");
  box.querySelectorAll("[data-id]").forEach((b) =>
    b.addEventListener("click", () => openJob(b.getAttribute("data-id")))
  );
}

